auto cost = vector(101, vector(101, vector<int>(101, -1)));

void calc() {
    cost[0][0][0] = 0;
    auto cur_v = vector<array<char, 3>>();
    cur_v.push_back({0, 0, 0});
    auto cnt = 0;

    while (!cur_v.empty()) {
        ++cnt;
        auto new_v = vector<array<char, 3>>();
        for (const auto &[a, b, c] : cur_v) {
            for (const auto [da, db, dc] : tps) {
                const auto na = static_cast<char>(a + da);
                const auto nb = static_cast<char>(b + db);
                const auto nc = static_cast<char>(c + dc);
                if (na > 100 || nb > 100 || nc > 100)
                    continue;
                if (cost[na][nb][nc] != -1)
                    continue;
                cost[na][nb][nc] = cnt;
                new_v.push_back({na, nb, nc});
            }
        }
        swap(cur_v, new_v);
    }
}


void solve() {
    const auto [a, b, c] = reads<3>();
    cout << cost[a][b][c] << endl;
}


int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);
    calc();
    auto [t] = reads<1>();
    while (t--)
        solve();
    return 0;
}
